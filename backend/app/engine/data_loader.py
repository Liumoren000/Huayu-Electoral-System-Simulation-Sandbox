class DataLoader:
    def __init__(self):
        self._cities: list[City] = []
        self._load_cities()

    def _get_province_name(self, city_id: str) -> str:
        code = city_id[:2]
        return PROVINCE_CODE_MAP.get(code, "未知")

    def _load_cities(self):
        for raw in CHINA_CITIES_RAW:
            region_type = self._classify_region(raw[3])
            province_name = self._get_province_name(raw[0])
            self._cities.append(City(
                id=raw[0], name=raw[1], name_en=raw[2],
                province=province_name,
                population=raw[4] * 10000,
                gdp_per_capita=raw[5] * 10000,
                urbanization_rate=raw[6],
                aging_rate=raw[7],
                education_index=raw[8],
                primary_industry_pct=raw[9],
                secondary_industry_pct=raw[10],
                tertiary_industry_pct=raw[11],
                region_type=region_type,
                ethnic_share=_ethnic_share_for(raw[0]),
            ))

    def _classify_region(self, province: str) -> str:
        coastal = {"华东", "华南"}
        western = {"西南", "西北"}
        northeast = {"东北"}
        if province in coastal:
            return "coastal"
        elif province in western:
            return "western"
        elif province in northeast:
            return "northeast"
        return "inland"

    def get_city_data(self, year: int = 2023) -> CityData:
        # 研究年代库：收录的年代使用年代预设参数，其余年份沿用旧版线性折算
        from .eras import get_era, apply_era_city

        era = get_era(year)
        if era:
            cities = [apply_era_city(c, era) for c in self._cities]
            total_pop = sum(c.population for c in cities)
            return CityData(year=year, cities=cities, total_population=total_pop)

        year_factor = 1.0 + (year - 2020) * 0.01
        cities = []
        for c in self._cities:
            adjusted = c.model_copy()
            adjusted.gdp_per_capita *= year_factor
            adjusted.population = int(adjusted.population * (1 + (year - 2020) * 0.001))
            cities.append(adjusted)
        total_pop = sum(c.population for c in cities)
        return CityData(year=year, cities=cities, total_population=total_pop)
